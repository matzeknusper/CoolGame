// Calibrates the horde mode. For every horde level it
//   1. measures how many Wusels per second a competent bot gets through the gates (no enemies),
//   2. searches the largest horde (as a fraction of that throughput) the bot still beats on
//      every seed with the expected upgrades,
// and writes the resulting kill rates to src/hordeTable.js, from which the level generator
// sizes the horde. Run it again whenever the horde gate layouts, the enemy rules or the upgrade
// formulas change:  node tools/calibrate.mjs
import { writeFileSync } from 'node:fs';
import { makeHordeLevel, hordeEq, HORDE_LEVELS } from '../src/levels.js';
import { Sim, Bot } from '../src/sim.js';
import { STATE } from '../src/config.js';

export function expectedUpgrades(n) {
  return { rate: Math.min(20, Math.floor(n * 0.3)), multi: Math.min(15, Math.floor(n * 0.24)), mega: Math.min(15, Math.floor(n * 0.15)), shield: Math.min(15, Math.floor(n * 0.15)), coins: 0 };
}

const SEEDS = 5;
const FACTORS = [1.15, 1.0, 0.88, 0.76, 0.66, 0.56, 0.47, 0.39, 0.32, 0.26];
const MARGIN = 0.85;
const dt = 1 / 60;

function throughput(h) {
  let sum = 0;
  for (let k = 0; k < 3; k++) {
    const sim = new Sim(makeHordeLevel(h, 1), expectedUpgrades(hordeEq(h)), k + 1, { sandbox: true });
    const bot = new Bot(sim, 0.8, k * 31 + h);
    let start = 0;
    for (let t = 0; t < 40; t += dt) {
      bot.update(dt); sim.step(dt); sim.evn = 0;
      if (Math.abs(t - 10) < dt / 2) start = sim.throughput;
    }
    sum += (sim.throughput - start) / 30;
  }
  return sum / 3;
}

// does the bot beat the level on every seed (and keep at least 40% shield on average)?
function beats(h, flow) {
  let shield = 0;
  for (let k = 0; k < SEEDS; k++) {
    const sim = new Sim(makeHordeLevel(h, flow), expectedUpgrades(hordeEq(h)), k + 1);
    const bot = new Bot(sim, 0.8, k * 17 + h);
    let t = 0;
    while (sim.state < STATE.WON && t < 160) { bot.update(dt); sim.step(dt); sim.evn = 0; t += dt; }
    if (sim.state !== STATE.WON) return false;
    shield += sim.shield / sim.shieldMax;
  }
  return shield / SEEDS >= 0.4;
}

const table = [];
const from = Number(process.argv[2] || 1), to = Number(process.argv[3] || HORDE_LEVELS);
for (let h = from; h <= to; h++) {
  const base = throughput(h);
  let f = FACTORS.find((x) => beats(h, base * x)) || FACTORS[FACTORS.length - 1] * 0.8;
  const flow = Math.round(base * f * MARGIN * 10) / 10;
  table.push(flow);
  console.log(`horde ${String(h).padStart(2)}: throughput ${base.toFixed(1).padStart(6)}  factor ${f.toFixed(2)}  ->  ${flow}`);
}
if (from === 1 && to === HORDE_LEVELS) {
  const out = `// GENERATED by tools/calibrate.mjs - do not edit by hand.\n// Kill rate (hp per second) each horde level 1..${HORDE_LEVELS} is sized for: the largest horde a competent\n// bot with the expected upgrades beats on every seed.\nexport const HORDE_FLOW = [${table.join(', ')}];\n`;
  writeFileSync(new URL('../src/hordeTable.js', import.meta.url), out);
  console.log('written src/hordeTable.js');
}
